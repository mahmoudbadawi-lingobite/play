#!/usr/bin/env python3
"""
Cut a generated sheet of props into PNGs, register them in props.json and regenerate the shop SQL.

  python3 tools/slice_props.py sheet.png --slot head --cols 4 --rows 2 --names "party-hat,crown,flower-wreath,bow" \
          [--titles "Party Hat,Golden Crown,Flower Wreath,Big Bow"] [--prices 80,400,150,60]
  python3 tools/slice_props.py --rebuild          # only regenerate the SQL after editing props.json by hand

--slot   head | face | neck | back
--names  ids (lowercase, letters/digits/dashes), one per prop in reading order (left to right, top to bottom)
Empty cells are skipped. Re-using an id replaces its picture but keeps the placement numbers you tuned in props.json.

Outputs:  public/monster-quest/props/<id>.png (trimmed, transparent, max 512 px)
          public/monster-quest/props/props.json      (the list the game reads)
          supabase/monster_quest_props.sql           (run in Supabase SQL editor to put the props in the shop)
Needs Pillow (pip install pillow).
"""
import argparse, json, os, re, sys
from collections import deque
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PROPS_DIR = os.path.join(ROOT, 'public', 'monster-quest', 'props')
JSON_PATH = os.path.join(PROPS_DIR, 'props.json')
SQL_PATH = os.path.join(ROOT, 'supabase', 'monster_quest_props.sql')
DEFAULT_PRICE = {'head': 100, 'face': 80, 'neck': 80, 'back': 150}

def remove_bg(im, tol=60):
    im = im.convert('RGBA'); px = im.load(); w, h = im.size
    if min(px[x, y][3] for x in (0, w - 1) for y in (0, h - 1)) < 20:
        return im
    bg = px[0, 0][:3]
    close = lambda c: sum(abs(c[i] - bg[i]) for i in range(3)) <= tol * 3 // 2
    seen = bytearray(w * h); q = deque((x, y) for x in range(w) for y in (0, h - 1)); q.extend((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        if x < 0 or y < 0 or x >= w or y >= h or seen[y * w + x]: continue
        seen[y * w + x] = 1
        if not close(px[x, y][:3]): continue
        px[x, y] = (0, 0, 0, 0); q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    return im

def load():
    if os.path.exists(JSON_PATH):
        return json.load(open(JSON_PATH, encoding='utf-8'))
    return {'props': []}

def sql_text(props):
    q = lambda s: "'" + s.replace("'", "''") + "'"
    rows = []
    for i, p in enumerate(props):
        data = json.dumps({'prop': p['id']}, separators=(',', ':'))
        rows.append(f"({q('pr_' + p['id'])},{q('prop_' + p['slot'])},{q(p.get('name', p['id']))},{int(p.get('price', DEFAULT_PRICE[p['slot']]))},null,1,{q(data)}::jsonb,{400 + i},true)")
    out = ["-- Generated by tools/slice_props.py from public/monster-quest/props/props.json. Safe to re-run any time.", "begin;",
           "update public.mq_cosmetics set active = false where key like 'pr\\_%' and slot like 'prop\\_%';"]
    if rows:
        out += ["insert into public.mq_cosmetics (key, slot, name, price_coins, price_gems, unlock_level, data, sort, active) values", ",\n".join(rows),
                "on conflict (key) do update set slot=excluded.slot, name=excluded.name, price_coins=excluded.price_coins, price_gems=excluded.price_gems,",
                "  unlock_level=excluded.unlock_level, data=excluded.data, sort=excluded.sort, active=true;"]
    out += ["grant execute on all functions in schema public to authenticated;", "commit;", ""]
    return "\n".join(out)

def save(data):
    os.makedirs(PROPS_DIR, exist_ok=True)
    json.dump(data, open(JSON_PATH, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    open(SQL_PATH, 'w', encoding='utf-8').write(sql_text(data['props']))
    print(f"props.json: {len(data['props'])} props; SQL written to {os.path.normpath(SQL_PATH)}")

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('sheet', nargs='?'); ap.add_argument('--slot', choices=list(DEFAULT_PRICE)); ap.add_argument('--cols', type=int, default=1); ap.add_argument('--rows', type=int, default=1)
    ap.add_argument('--names'); ap.add_argument('--titles'); ap.add_argument('--prices'); ap.add_argument('--rebuild', action='store_true')
    a = ap.parse_args()
    data = load()
    if a.rebuild: return save(data)
    if not (a.sheet and a.slot and a.names): ap.error('need sheet, --slot and --names (or --rebuild)')
    names = [n.strip() for n in a.names.split(',') if n.strip()]
    for n in names:
        if not re.fullmatch(r'[a-z0-9][a-z0-9-]*', n): sys.exit(f'bad id "{n}": use lowercase letters, digits and dashes')
    titles = [t.strip() for t in a.titles.split(',')] if a.titles else [n.replace('-', ' ').title() for n in names]
    prices = [int(p) for p in a.prices.split(',')] if a.prices else [DEFAULT_PRICE[a.slot]] * len(names)
    if not (len(titles) == len(prices) == len(names)): sys.exit('--names, --titles and --prices need the same number of items')
    im = remove_bg(Image.open(a.sheet)); cw, ch = im.width // a.cols, im.height // a.rows
    found = []
    for r in range(a.rows):
        for c in range(a.cols):
            cell = im.crop((c * cw, r * ch, (c + 1) * cw, (r + 1) * ch))
            bb = cell.getchannel('A').point(lambda v: 255 if v > 24 else 0).getbbox()
            if bb and (bb[2] - bb[0]) * (bb[3] - bb[1]) > 400: found.append(cell.crop(bb))
    if len(found) != len(names): sys.exit(f'found {len(found)} props in the sheet but got {len(names)} names. Check --cols/--rows and --names.')
    os.makedirs(PROPS_DIR, exist_ok=True)
    byid = {p['id']: p for p in data['props']}
    for img, pid, title, price in zip(found, names, titles, prices):
        k = min(1.0, 512 / max(img.size)); img = img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)
        img.save(os.path.join(PROPS_DIR, pid + '.png'))
        old = byid.get(pid, {}); entry = {**old, 'id': pid, 'name': title if (a.titles or not old) else old.get('name', title), 'slot': a.slot, 'file': pid + '.png', 'price': price if (a.prices or not old) else old.get('price', price), 'ar': round(img.height / img.width, 3)}
        byid[pid] = entry
    order = [p['id'] for p in data['props']] + [n for n in names if n not in {p['id'] for p in data['props']}]
    data['props'] = [byid[i] for i in order]
    save(data)
    print('Next: run supabase/monster_quest_props.sql in the Supabase SQL editor, then refresh the game.')
    print('If a prop sits too high/low or is too big/small, edit its w / oy / ox in props.json (see docs/PROP_PROMPTS.md).')

if __name__ == '__main__':
    main()
