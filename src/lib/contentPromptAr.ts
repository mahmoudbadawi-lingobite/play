import type { PromptOptions } from './contentPrompt';

/** Arabic versions of the content prompts. JSON keys stay in English (the app reads them); every instruction and value is Arabic. */

const FORMAT_AR: Record<string, { term: string; clue: string }> = {
  vocabulary: { term: 'الكلمة (كلمة واحدة أو عبارة قصيرة من 1 إلى 3 كلمات)', clue: 'تعريف بسيط للكلمة، أو جملة قصيرة فيها ___ مكان الكلمة' },
  grammar: { term: 'الإجابة الصحيحة (كلمة أو حرف أو صيغة قصيرة)', clue: 'جملة فيها ___ مكان الإجابة، أو سؤال قصير عن القاعدة' },
  reading: { term: 'إجابة قصيرة عن سؤال الفهم', clue: 'سؤال فهم قصير' },
  spelling: { term: 'الكلمة مكتوبة بإملاء صحيح (كلمة واحدة)', clue: 'تلميح قصير يدل على الكلمة دون ذكرها (معناها أو جملة فيها ___)' },
};

function header(o: PromptOptions, typeLine: string): string[] {
  const subject = o.focus?.subject.trim() || o.subject.trim() || 'اللغة العربية';
  return [
    `أنت معلّم ${subject} خبير تُعدّ محتوى لعبة تعليمية.`,
    '',
    'المحتوى',
    `العنوان: ${o.title.trim() || '[اكتب العنوان في الصفحة أولاً]'}`,
    typeLine,
    `الطلاب: الصف ${o.grade} (نحو ${o.grade + 5} سنوات)`,
    `المادة: ${subject}`,
    ...(o.focus?.domains?.length ? [`المجال: ${o.focus.domains.join('، ')}`] : []),
    ...(o.focus?.skills?.length
      ? [`المهارات المطلوبة: ${o.focus.skills.map((k) => (k.hint ? `${k.name} (${k.hint})` : k.name)).join('؛ ')}`,
         o.focus.skills.length > 1 ? 'وزّع العناصر على هذه المهارات، وليخدم كل عنصر إحداها لا الموضوع العام فقط.' : 'يجب أن يخدم كل عنصر هذه المهارة تحديداً.']
      : []),
    ...(o.topic.trim() ? [`الموضوع: ${o.topic.trim()}`] : []),
  ];
}

function source(o: PromptOptions): string[] {
  const raw = o.rawText.trim();
  return [
    '',
    'المادة المصدرية',
    o.hasAttachment
      ? `نصي مرفق في هذه المحادثة (ملف أو صورة). اقرأه أولاً بما فيه النص داخل الصور، واعتمد عليه وحده، وتجاهل أي إجابات مكتوبة على الصفحة.${raw ? `\nواستعن أيضاً بهذه الملاحظات:\n${raw}` : ''}`
      : raw || 'لم يُقدَّم نص: اكتب محتوى أصلياً قصيراً يناسب المستوى والموضوع.',
  ];
}

export function buildArabicStandardPrompt(o: PromptOptions): string {
  const f = FORMAT_AR[o.skill] ?? FORMAT_AR.vocabulary;
  return [
    ...header(o, `نوع العناصر: ${o.skill === 'reading' ? 'فهم قرائي' : o.skill === 'grammar' ? 'قواعد' : o.skill === 'spelling' ? 'إملاء' : 'مفردات'}`),
    `عدد العناصر: ${o.count} بالضبط`,
    ...source(o),
    '',
    'ماذا يحتوي كل عنصر',
    `• "term" - ${f.term}`,
    `• "clue" - ${f.clue}`,
    '',
    'القواعد',
    `• أنشئ ${o.count} عنصراً بالضبط واجعل كل "term" مختلفاً عن غيره.`,
    '• اجعل الكلمات قصيرة (غالباً من 1 إلى 3 كلمات ولا تزيد عن 30 حرفاً)، مكتوبة كما يجب أن يكتبها الطالب. دون ترقيم أو نقاط في آخرها.',
    '• لا تضع الإجابة (term) داخل التلميح (clue).',
    `• استخدم لغة عربية فصحى بسيطة تناسب الصف ${o.grade}، وليكن كل تلميح أقل من 120 حرفاً تقريباً. شكّل الكلمة فقط حيث يلزم لمنع اللبس.`,
    '• تبني اللعبة الخيارات الخاطئة من كلمات العناصر الأخرى، فاجعل كل الكلمات من النوع نفسه (مثلاً: كلها أفعال ماضية أو كلها أسماء أماكن) لتبدو الخيارات مقنعة.',
    '• نص عادي فقط: دون صور أو روابط أو رموز تعبيرية أو markdown داخل الحقول.',
    '• إذا احتوت قيمة على علامة اقتباس مزدوجة فاكتبها \\" حتى يبقى JSON صحيحاً.',
    '',
    'تنسيق المخرجات',
    'أجب بكتلة شيفرة واحدة تحتوي JSON صحيحاً ولا شيء غيرها (دون تحية أو شرح قبلها أو بعدها). المفاتيح بالإنجليزية والقيم بالعربية، بهذا الشكل بالضبط:',
    '',
    '```json',
    '{',
    '  "items": [',
    '    { "term": "<الإجابة>", "clue": "<السؤال أو التلميح>" },',
    '    { "term": "<الإجابة>", "clue": "<السؤال أو التلميح>" }',
    '  ]',
    '}',
    '```',
    '',
    `أضف كائناً واحداً إلى "items" لكل عنصر من العناصر الـ ${o.count}.`,
  ].join('\n');
}

export function buildArabicRichPrompt(o: PromptOptions, kind: 'listening' | 'reading'): string {
  return [
    ...header(o, `النوع: ${kind === 'listening' ? 'نشاط مقطع صوتي (يُقرأ النص بصوت عالٍ ويجيب الطلاب بالاستماع)' : 'فهم قرائي (نص قصير ثم سؤال واحد)'}`),
    `عدد العناصر: عنصر واحد لكل مقطع، بحد أقصى ${o.count}.`,
    ...source(o),
    '',
    'كيف تبني العناصر',
    kind === 'listening'
      ? '• قسّم النص إلى مقاطع متتابعة من جملتين إلى ثلاث جمل (نحو 25 إلى 45 كلمة) بحسب ترتيب النص، بحيث تغطي النص كله. كل مقطع عنصر واحد بالضبط.\n• "audio" = المقطع بنصه حرفياً. سيقرؤه التطبيق بصوت عالٍ، فلا إرشادات مسرحية ولا ترقيم ولا كلمة "سؤال".\n• لا تكرر المقطع داخل السؤال: على الطالب أن يستمع لا أن يقرأ.'
      : '• قسّم النص إلى فقرات متتابعة من 3 إلى 5 جمل بحسب الترتيب، بحيث تغطي النص كله. كل فقرة عنصر واحد بالضبط.\n• "passage" = الفقرة بنصها حرفياً.',
    '• "clue" = سؤال واحد عن هذا المقطع فقط، مفهوم بذاته ويمكن الإجابة عنه من المقطع وحده.',
    '• "term" = الإجابة الصحيحة، قصيرة (من كلمة إلى 8 كلمات)، مأخوذة من المقطع أو مدعومة به بوضوح.',
    '• "wrong" = ثلاث إجابات خاطئة بالضبط: معقولة، وبطول الإجابة الصحيحة تقريباً، وخاطئة بوضوح.',
    '• نوّع أنواع الأسئلة بين المقاطع: الفكرة العامة، معلومة صريحة، من قال أو فعل، لماذا، ماذا حدث بعد ذلك.',
    '• نص عادي فقط، دون رموز تعبيرية أو markdown. اكتب علامة الاقتباس المزدوجة داخل القيمة هكذا \\".',
    '',
    'تنسيق المخرجات',
    'أجب بكتلة شيفرة واحدة تحتوي JSON صحيحاً ولا شيء غيرها. المفاتيح بالإنجليزية والقيم بالعربية، بهذا الشكل بالضبط:',
    '',
    '```json',
    '{',
    '  "items": [',
    kind === 'listening'
      ? '    { "audio": "<المقطع من جملتين إلى ثلاث>", "clue": "<السؤال>", "term": "<الإجابة الصحيحة>", "wrong": ["<خطأ 1>", "<خطأ 2>", "<خطأ 3>"] }'
      : '    { "passage": "<الفقرة>", "clue": "<السؤال>", "term": "<الإجابة الصحيحة>", "wrong": ["<خطأ 1>", "<خطأ 2>", "<خطأ 3>"] }',
    '  ]',
    '}',
    '```',
  ].join('\n');
}
